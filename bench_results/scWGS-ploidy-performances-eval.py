"""
https://chatgpt.com/c/6a947653-f9f0-83ea-9bac-a97e08c5b168

Final-manuscript plotting front-end for scWGS-ploidy-performances-eval_v02.py.

Place this file beside ``scWGS-ploidy-performances-eval_v02.py`` in
``bench_results/`` and invoke it with the same CLI arguments as v02.  Data
loading, filtering, row ordering, benchmark calculations, and TSV export are
still performed by v02; this file replaces only the main-text plotting layer.

Visual encoding
---------------
* Balloon DIAMETER = percentage of cells whose ploidy estimate is within ±0.5
  of the ground truth.
* Balloon COLOUR INTENSITY = log10(sample size), by default log10 of the
  number of finite/evaluable cells contributing to that percentage
  (``n_cells_finite``).
* Red × = a result was expected but is missing / failed.
* Grey hatched block = method is not applicable to that panel.

Method-specific rules
---------------------
* scAbsolute: shown once, because copy-number cap vs no-cap does not apply; it
  produces a final ploidy estimate rather than a CNV profile.
* CHISEL in ACT: shown as not applicable because phased genotypes are not
  readily available for the ACT samples.

The combined 2×2 figure follows common manuscript conventions: lowercase bold
panel letters (a–d) at the upper-left outside each axes, no embedded figure
headline/caption, fully horizontal, vertically interleaved method labels, explicit CapAt10 labels, and one shared legend below the panels, and collision-free two-tier x-axis labels.

Statistical tests (ONE pooled family over all donors)
-----------------------------------------------------
[REV v4] After the figures, the ploidy benchmark is tested ONCE over the
pooled set of ALL donors from ALL four panels (COLO-829, HCC1395, HeLa,
ACT).  The previous behaviour -- one independent test family per panel --
split the donors across four small tests, which clearly reduces statistical
power.  The germline-derived row labels are reused across the three
cell-line panels (the label omits the emulated cell line), so the same donor
legitimately occurs in three panels: a naive concatenation of the panels
would duplicate (dataset, method) keys and break the per-sample pairing
inside stat_tests, and counting one donor once per panel would violate the
independence of the samples.  Pooling therefore first aggregates, for every
donor, all of that donor's per-dataset evaluations -- across the panels,
sample types and read lengths in which that donor occurs -- into ONE
observation per method (the median, matching the cluster aggregation used
previously; non-failed rows are preferred).  Each donor then denotes exactly
one independent sample, and the pooled table keeps one row per (donor,
method), which restores the pivot invariant required by stat_tests.  The
Friedman omnibus and the two-sided Wilcoxon signed-rank post-hoc tests
(paired by donor, Holm-corrected within each (scenario, metric) family over
the whole donor pool, effect sizes, BCa bootstrap CIs) are run on this pooled
table and written to a single set of ``<output>.pooled.stats.*.tsv`` files.
``--stats-only`` re-runs the pooled tests on the existing
``<output>_pct_within_long.tsv`` without redrawing the figures, and
``--latex-table`` prints one booktabs table from
``<output>.pooled.stats.pairwise.tsv``.

No new graphical content is generated by this revision: the figure layer is
unchanged, and the pooled analysis writes only TSV tables (plus the optional
LaTeX table on stdout).
"""

