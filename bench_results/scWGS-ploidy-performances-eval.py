def _panel_letter(fig, ax, letter, fontsize=13.5):
    """Large bold lowercase panel label, just outside the upper-left axes corner."""
    if not letter:
        return
    bbox = ax.get_position()
    fig.text(
        bbox.x0 - 0.030,
        bbox.y1 + 0.008,
        str(letter).lower(),
        ha="left",
        va="bottom",
        fontsize=fontsize,
        fontweight="bold",
        color=TEXT,
    )


